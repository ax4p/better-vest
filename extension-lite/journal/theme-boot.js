(function () {
    try {
        var name = localStorage.getItem('bv-journal-theme');
        /* Better Vest, written by Astral. Copyright (c) 2026. Reuse needs written permission from Astral. bv-89dd51a7 */ var css = localStorage.getItem('bv-journal-themecss');
        var root = document.documentElement;
        if (name) root.setAttribute('data-theme', name);
        if (css) {
            var s = document.createElement('style');
            s.id = 'theme-vars';
            s.textContent = css;
            /* @preserve Copyright (c) 2026 Astral (@ax4p). Better Vest 9.5.5. bv-fe397cd7 */ document.head.appendChild(s);
        }
        if (localStorage.getItem('bv-journal-motion') === 'off') root.setAttribute('data-reduce-motion', '1');
    } catch (e) {  }
})();
