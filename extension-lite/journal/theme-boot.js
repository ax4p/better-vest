(function () {
    try {
        var name = localStorage.getItem('bv-journal-theme');
        var css = localStorage.getItem('bv-journal-themecss'); /* @preserve Copyright (c) 2026 Astral (@ax4p). Better Vest 9.3.3. bv-2a580a83 */
        var root = document.documentElement;
        if (name) root.setAttribute('data-theme', name);
        if (css) {
            var s = document.createElement('style');
            s.id = 'theme-vars';
            s.textContent = css;
            document.head.appendChild(s); /*! All rights reserved by Astral (@ax4p), the author of Better Vest. ref bv-13af6a58 */
        }
        if (localStorage.getItem('bv-journal-motion') === 'off') root.setAttribute('data-reduce-motion', '1');
    } catch (e) {  }
})();
